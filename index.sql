CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    endereco VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES public.clientes(id),
    data TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    valor FLOAT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.tamanhos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(50) NOT NULL,
    preco_base FLOAT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.bordas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(50) NOT NULL,
    preco_adicional FLOAT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.coberturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(50) NOT NULL,
    preco_adicional FLOAT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.bebidas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL,
    preco_adicional FLOAT NOT NULL,
    tamanho VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.condionamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(50) NOT NULL,
    preco_adicional FLOAT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.itens_pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES public.pedidos(id),
    id_tamanho BIGINT NOT NULL REFERENCES public.tamanhos(id),
    id_borda BIGINT NOT NULL REFERENCES public.bordas(id),
    quantidade INT NOT NULL,
    observacao VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.itens_coberturas (
    id_item_pedido BIGINT NOT NULL REFERENCES public.itens_pedidos(id),
    id_cobertura BIGINT NOT NULL REFERENCES public.coberturas(id)
);

CREATE TABLE IF NOT EXISTS public.itens_bebidas (
    id_item_pedido BIGINT NOT NULL REFERENCES public.itens_pedidos(id),
    id_bebida BIGINT NOT NULL REFERENCES public.bebidas(id)
);

CREATE TABLE IF NOT EXISTS public.itens_condionamentos (
    id_item_pedido BIGINT NOT NULL REFERENCES public.itens_pedidos(id),
    id_condionamento BIGINT NOT NULL REFERENCES public.condionamentos(id)
);